/* These are bootstrap dictionaries, separate from Apple's unchanged NSXPC
 * handshake/protocol. Every received dictionary must pass the actual peer
 * identity gate before any endpoint or nonce is accepted.
 *
 * configuration:     {privateMethod:STRING}                            [1]
 * configuration-ack: {privateMethod:STRING,nonce:UINT64,status:INT64}   [3]
 * endpoint:          {privateMethod:STRING,serviceIdentifier:STRING,
 *                     nonce:UINT64,serviceEndpoint:XPC_ENDPOINT}      [4]
 * endpoint-ack:      {privateMethod:STRING,nonce:UINT64,status:INT64}   [3]
 * nonce is nonzero, generated by the owning parent, never from environment.
 * A zero bootstrap status says only that the real transport was accepted;
 * it never substitutes for Apple's task handshake or GPU completion. */

/* Root generates this immutable definition from the actual native task and
 * new canonical installation. No caller or environment supplies code pins.
 * Parent SHA/CD are intentionally absent: the parent authenticates signed
 * task pins; the task authenticates its capability-owning actual parent via
 * canonical path, full disk signature/pages, kernel CD/audit identity, and
 * genuine virtualization permissions, avoiding a signing dependency cycle. */
typedef struct {
    uint32_t version;
    uid_t ownerUID;
    const char *canonicalExecutablePath;
    const char *nativeMainUUID;
    uintptr_t nativeMainRVA;
    uint32_t admittedMainBranchWord;
    uintptr_t nativeDelegateClassRVA;
    uintptr_t nativeHostLogRVA;
    const char *canonicalDefaultMetallibPath;
    const char *defaultMetallibSHA256;
    uint64_t defaultMetallibBytes;
    const char *canonicalParentBundlePath;
    const char *parentExecutableName;
} VM27OwnedGPUTaskServerProfileV1;

