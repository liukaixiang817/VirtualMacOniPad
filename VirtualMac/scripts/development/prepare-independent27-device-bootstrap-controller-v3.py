def ready_gate(packet, ready_path):
    ready = json.loads(ready_path.read_bytes())
    need(ready.get('readyForRootSerialDispatch') is True, 'Root review ready gate absent')
    need(ready['packetCandidate'] == pin(packet/'candidate.json') and ready['packetFreeze'] == pin(packet/'freeze.json'), 'exact ready packet')
    freeze = json.loads(exact(ready['packetFreeze']).read_bytes())
    for row in freeze['files']:
        exact(row)
    need(ready['controller'] == pin(packet/'control.py') == pin(__file__), 'exact reviewed controller')
    need(len(ready['independentReviews']) >= 1, 'independent concrete controller review required')
    for row in ready['independentReviews']:
        review = json.loads(exact(row).read_bytes())
        need(review.get('findings') == [] and review.get('controllerPacketCandidate') == pin(packet/'candidate.json'), 'review exact packet without unresolved findings')
    scope = json.loads((packet/'scope.json').read_bytes())
    auth = json.loads(exact(ready['specificUserAuthorization']).read_bytes())
    need(auth.get('authorized') is True and auth.get('humanUserAuthorization') is True and
         auth['scope'] == pin(packet/'scope.json') and auth['trustCacheCDHashes'] == scope['trustCacheCDHashes'] and
         auth['trustCacheRegistrationCount'] == 140 and auth['initializationExternalWallSeconds'] == 45,
         'new exact human authorization for persistent 140-hash set and bounded initialization')
    validate_archive((packet/'products.tar').read_bytes(), scope)
    return ready, scope


def run_remote(script, data, root, password):
    env = dict(os.environ)
    env.update(VIRTUALMAC_SSH_PASSWORD=password, SSH_ASKPASS='/private/tmp/virtualmac-ipad-tools/ssh-askpass',
               SSH_ASKPASS_REQUIRE='force', DISPLAY='virtualmac-debug')
    command = ('sudo -k -S -p "" ' if root else '')+'/var/jb/bin/sh -c '+shlex.quote(script)
    argv = ['ssh', '-p', '2221', '-o', 'ConnectTimeout=8', '-o', 'ControlMaster=no', '-o', 'ControlPath=none',
            '-o', 'UserKnownHostsFile=/private/tmp/virtualmac-ipad-known-hosts', '-o', 'StrictHostKeyChecking=yes',
            'mobile@127.0.0.1', command]
    send = (password+'\n').encode()+data if root else data
    try:
        result = subprocess.run(argv, input=send, env=env, capture_output=True, timeout=55)
        return result.returncode, result.stdout, result.stderr, None
    except subprocess.TimeoutExpired as error:
        return 124, error.stdout or b'', error.stderr or b'', 'SSH 55-second timeout; no retry'
    except OSError:
        return 125, b'', b'', 'SSH transport failed; no retry'
    finally:
        env.pop('VIRTUALMAC_SSH_PASSWORD', None)


def prior_receipt(packet, action, success):
    output = packet/'device-receipts'/action
    request = json.loads((output/'request.json').read_bytes())
    receipt = json.loads((output/'receipt.json').read_bytes())
    need(request['packetCandidate'] == pin(packet/'candidate.json') and
         receipt['request'] == pin(output/'request.json'), 'exact prior action packet/receipt')
    need(receipt['stdout'] == pin(output/'stdout') and receipt['stderr'] == pin(output/'stderr'), 'exact prior output')
    if success:
        need(receipt['transportExit'] == 0, 'prior action failed: '+action)
    return [pin(output/'request.json'), pin(output/'receipt.json')]


def dispatch(args):
    packet = args.packet.resolve()
    need(packet.parent == N and pathlib.Path(__file__).resolve() == packet/'control.py', 'dispatch only exact packet controller')
    ready, scope = ready_gate(packet, args.ready.resolve())
    prior = []
    previous = {'stage': 'health', 'trust-1': 'stage', 'launch': 'trust-7', 'post': 'launch'}.get(args.action)
    if args.action in TRUST_ACTIONS and args.action != 'trust-1':
        previous = TRUST_ACTIONS[TRUST_ACTIONS.index(args.action)-1]
    if previous:
        prior = prior_receipt(packet, previous, success=args.action != 'post')
    output_root = packet/'device-receipts'
    output_root.mkdir(mode=0o700, exist_ok=True)
    need(not output_root.is_symlink(), 'ordinary local receipt directory')
    output = output_root/args.action
    need(not output.exists(), 'serial action never repeated')
    lock = packet/'dispatch.lock'
    fd = os.open(lock, os.O_WRONLY|os.O_CREAT|os.O_EXCL, 0o600)
    identity = os.fstat(fd)
    try:
        output.mkdir(mode=0o700)
        marker = packet/(args.action+'-dispatched.json')
        with os.fdopen(os.open(marker, os.O_WRONLY|os.O_CREAT|os.O_EXCL, 0o600), 'w') as stream:
            json.dump({'action': args.action, 'packetCandidate': pin(packet/'candidate.json'),
                       'startedUTC': datetime.datetime.now(datetime.timezone.utc).isoformat()}, stream)
        data = (packet/'products.tar').read_bytes() if args.action == 'stage' else b''
        if args.action == 'post':
            raw = (output_root/'launch/stdout').read_text(errors='replace')
            found = {}
            for kind, pid, ppid, start, path in re.findall(r'^OWN_(APP|CHILD)_ID ([0-9]+) ([0-9]+) 501 ([a-f0-9]{64}) (\S+)$', raw, re.M):
                need(kind not in found and int(pid) > 1 and path == (APP_MAIN if kind == 'APP' else CHILD_MAIN), 'exact captured own identity')
                found[kind] = (pid, ppid, start)
            parent = found.get('APP', ('0', '1', 'none'))
            child = found.get('CHILD', ('0', '0', 'none'))
            need(parent[1] == '1' and (child[0] == '0' or child[1] == parent[0]), 'captured actual child PPID binding')
            data = f'{parent[0]} {parent[2]} {child[0]} {child[2]}\n'.encode()
        script = (packet/(args.action+'.sh')).read_text()
        request = {'action': args.action, 'packetCandidate': pin(packet/'candidate.json'),
                   'ready': pin(args.ready.resolve()), 'script': pin(packet/(args.action+'.sh')),
                   'priorPins': prior, 'inputBytes': len(data), 'inputSHA256': digest(data),
                   'root': args.action != 'launch', 'guestBootRequested': False}
        dump(output/'request.json', request)
        password = getpass.getpass('iPad password: ')
        if args.action == 'launch':
            status, stdout, stderr, error = run_remote((packet/'register.sh').read_text(), b'', True, password)
            (output/'register.stdout').write_bytes(stdout)
            (output/'register.stderr').write_bytes(stderr)
            dump(output/'register-receipt.json', {'transportExit': status, 'transportError': error,
                 'script': pin(packet/'register.sh'), 'stdout': pin(output/'register.stdout'), 'stderr': pin(output/'register.stderr')})
            if status == 0:
                status, stdout, stderr, error = run_remote(script, data, False, password)
        else:
            status, stdout, stderr, error = run_remote(script, data, True, password)
        password = None
        (output/'stdout').write_bytes(stdout)
        (output/'stderr').write_bytes(stderr)
        receipt = {'action': args.action, 'finishedUTC': datetime.datetime.now(datetime.timezone.utc).isoformat(),
                   'transportExit': status, 'transportError': error, 'request': pin(output/'request.json'),
                   'stdout': pin(output/'stdout'), 'stderr': pin(output/'stderr'),
                   'guestBootRequested': False, 'trustCacheWithdrawalPerformed': False}
        dump(output/'receipt.json', receipt)
        print(json.dumps(receipt))
        print(stdout.decode(errors='replace')[-14000:])
        need(status == 0, 'bounded action failed; preserve receipt and perform exact post cleanup')
    finally:
        live = os.lstat(lock)
        need((live.st_dev, live.st_ino) == (identity.st_dev, identity.st_ino), 'serial lock identity changed')
        os.close(fd)
        os.unlink(lock)


