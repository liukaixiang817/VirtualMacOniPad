def need(value, reason):
    if not value:
        raise ValueError(reason)


def digest(data):
    return hashlib.sha256(data).hexdigest()


def pin(path):
    path = pathlib.Path(path)
    need(path.is_absolute() and '..' not in path.parts and path.is_relative_to(R), 'workspace absolute pin')
    need(path.is_file() and not path.is_symlink(), 'regular pinned file')
    need(all(not p.is_symlink() for p in [path, *path.parents] if p.is_relative_to(R)), 'no pin symlink ancestors')
    data = path.read_bytes()
    return {'path': str(path), 'bytes': len(data), 'sha256': digest(data)}


def exact(row):
    need(pin(row['path']) == row, 'exact pin changed: '+row['path'])
    return pathlib.Path(row['path'])


def dump(path, value):
    path.write_text(json.dumps(value, indent=2)+'\n')


def regular_tree(root):
    root = pathlib.Path(root)
    need(root.is_dir() and not root.is_symlink(), 'actual regular product directory')
    files = []
    for path in sorted(root.rglob('*')):
        need(not path.is_symlink() and (path.is_file() or path.is_dir()), 'ordinary product members only')
        if path.is_file():
            need(path.stat().st_nlink == 1, 'no host hardlinked product')
            files.append(path)
    return files


def safe_relative(value):
    p = pathlib.PurePosixPath(value)
    need(not p.is_absolute() and value == str(p) and all(x not in ('', '.', '..') for x in p.parts), 'canonical archive relative name')
    need(re.fullmatch(r'[A-Za-z0-9_.+@/\-]+', value) is not None, 'finite ordinary archive names')
    return p


def archive_bytes(rows, directories):
    stream = io.BytesIO()
    with tarfile.open(fileobj=stream, mode='w:', format=tarfile.USTAR_FORMAT) as archive:
        for name, mode in sorted(directories.items()):
            safe_relative(name)
            item = tarfile.TarInfo(name)
            item.type = tarfile.DIRTYPE
            item.uid = item.gid = 501
            item.mode = mode
            item.mtime = 0
            archive.addfile(item)
        for row in rows:
            safe_relative(row['archivePath'])
            data = exact(row['local']).read_bytes()
            item = tarfile.TarInfo(row['archivePath'])
            item.uid = item.gid = 501
            item.mode = row['mode']
            item.mtime = 0
            item.size = len(data)
            archive.addfile(item, io.BytesIO(data))
    return stream.getvalue()


def validate_archive(data, scope):
    expected = {name: ('directory', mode) for name, mode in scope['directories'].items()}
    expected.update({row['archivePath']: ('file', row['mode']) for row in scope['files']})
    by_name = {row['archivePath']: row for row in scope['files']}
    with tarfile.open(fileobj=io.BytesIO(data), mode='r:') as archive:
        items = archive.getmembers()
        need(len(items) == len(expected) and len({x.name.rstrip('/') for x in items}) == len(items), 'exact archive count and unique names')
        for item in items:
            name = item.name.rstrip('/')
            safe_relative(name)
            need(name in expected and item.uid == item.gid == 501 and item.mtime == 0 and
                 not item.linkname and not item.pax_headers, 'ordinary exact archive entry')
            kind, mode = expected[name]
            need(item.mode == mode and item.type == (tarfile.DIRTYPE if kind == 'directory' else tarfile.REGTYPE), 'exact archive kind/mode')
            if kind == 'directory':
                need(item.size == 0, 'empty directory member')
            else:
                row = by_name[name]
                contents = archive.extractfile(item).read()
                need(len(contents) == row['local']['bytes'] and digest(contents) == row['local']['sha256'], 'actual exact archive bytes')
    need(data == archive_bytes(scope['files'], scope['directories']), 'canonical USTAR without hidden extension members')


