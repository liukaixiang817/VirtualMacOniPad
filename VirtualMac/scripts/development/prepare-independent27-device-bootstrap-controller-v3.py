def prepare(args):
    out = args.output.resolve()
    need(out.parent == N and not out.exists(), 'fresh direct diagnostics packet')
    runtime_path = args.runtime_candidate.resolve()
    app_path = args.app_candidate.resolve()
    runtime = json.loads(runtime_path.read_bytes())
    app = json.loads(app_path.read_bytes())
    need(runtime['canonicalDeviceRoot'] == app['runtimeRoot'] == DEVICE_RUNTIME, 'same current actual Runtime3 root')
    need(app['runtimeCandidate'] == pin(runtime_path) and app['realCompiledManifestAnchor'] == runtime['anchorSource'], 'actual final App anchor matches exact runtime')
    need(app['actualCodeSigned'] and app['actualPrimaryPagesAndExternalSlotsVerified'] and runtime['actualProductPreflightPassed'], 'actual signed production product evidence')
    linked = json.loads(exact(app['sourceCandidate']).read_bytes())
    source = json.loads(exact(linked['sourceCandidate']).read_bytes())
    need(source.get('independentApplicationLogIsolated') is True and source.get('independentApplicationLog') == DEVICE_LOG and
         source.get('runtimeStartupUsesActualBackgroundSerialQueue') is True and source.get('URLAcceptanceIsStartupSuccess') is False,
         'isolated actual App8 background runtime-startup')
    health_freeze = json.loads((HEALTH.parent/'controller-freeze.json').read_bytes())
    exact(next(row for row in health_freeze['files'] if row['path'] == str(HEALTH)))
    manifest = plistlib.loads(exact(runtime['manifest']).read_bytes())
    actual_signatures = json.loads(exact(runtime['signatureVerification']).read_bytes())['actualSignedFiles']
    need(len(actual_signatures) == 139 and len(manifest['files']) == runtime['files'],
         'actual finite 139 signed images and exact current manifest count')
    firmware_names = {'AVPBooter.vmapple2.bin', 'AVPBooter.vresearch1.bin', 'AVPSEPBooter.vresearch1.bin',
                      'VZG11.fd', 'VZG21.fd'}
    firmware_rows = [row for row in manifest['files'] if row['path'].startswith('Firmware27/')]
    need({row['path'] for row in firmware_rows} == {'Firmware27/'+name for name in firmware_names} and
         len(firmware_rows) == 5 and all(row['kind'] == 'resource' for row in firmware_rows),
         'exact five genuine original27 firmware resources in final manifest')
    need(sum(row['kind'] == 'mach-o' for row in manifest['files']) == 139 and
         sum(row['kind'] == 'resource' for row in manifest['files']) == 9,
         '139 actual code images plus four registration/proof and five firmware resources')
    signature_by_path = {row['relativePath']: row for row in actual_signatures}
    root = pathlib.Path(runtime['runtimeRoot'])
    app_root = pathlib.Path(app['app'])
    all_runtime = regular_tree(root)
    all_app = regular_tree(app_root)
    need({str(p) for p in all_app} == {row['path'] for row in app['appFiles']}, 'exact signed App inventory')
    manifest_names = {row['path'] for row in manifest['files']} | {pathlib.Path(runtime['manifest']['path']).relative_to(root).as_posix()}
    need({p.relative_to(root).as_posix() for p in all_runtime} == manifest_names, 'exact runtime manifest plus manifest itself')
    rows = []
    for f in all_runtime:
        relative = f.relative_to(root).as_posix()
        p = pin(f)
        signature = signature_by_path.get(relative)
        if signature:
            need(signature['actualSignedFile'] == p and signature['allPrimaryPagesAndSpecialSlotsVerified'], 'actual runtime signature/file binding')
        else:
            need(relative not in signature_by_path, 'ordinary unsigned manifest resources')
        record = {'archivePath': 'runtime/'+relative, 'devicePath': DEVICE_RUNTIME+'/'+relative,
                  'local': p, 'mode': 0o700 if signature else 0o600}
        if signature:
            record['cdhash'] = signature['cdhash']
        rows.append(record)
    for f in all_app:
        relative = f.relative_to(app_root).as_posix()
        p = pin(f)
        need(p in app['appFiles'], 'actual signed App file')
        record = {'archivePath': 'VirtualMacIndependent27.app/'+relative, 'devicePath': DEVICE_APP+'/'+relative,
                  'local': p, 'mode': 0o755 if f == pathlib.Path(app['binary']['path']) else 0o644}
        if f == pathlib.Path(app['binary']['path']):
            need(app['actualSignature']['file'] == p, 'actual final main signature binding')
            record['cdhash'] = app['actualSignature']['cdhash']
