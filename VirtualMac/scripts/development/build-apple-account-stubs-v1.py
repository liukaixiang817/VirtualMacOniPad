#!/usr/bin/env python3
"""Assemble the position-independent guest policy; include no Apple binaries."""
import argparse
import importlib.util
from pathlib import Path
import struct
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[3]
SOURCE = ROOT / 'VirtualMac/vz/apple-account/VMAppleAccountSysctlStubV1.S'


def extract(data):
    if data[:4] != b'\xcf\xfa\xed\xfe': raise ValueError('not Mach-O64')
    offset, text, symbols = 32, None, None
    for _ in range(struct.unpack_from('<I', data, 16)[0]):
        command, size = struct.unpack_from('<II', data, offset)
        if command == 0x19:
            count = struct.unpack_from('<I', data, offset + 64)[0]
            for i in range(count):
                at = offset + 72 + i * 80
                if data[at:at + 16].rstrip(b'\0') != b'__text': continue
                address, length = struct.unpack_from('<QQ', data, at + 32)
                fileoff, _, _, relocations = struct.unpack_from('<IIII', data, at + 48)
                if relocations: raise ValueError('stub contains relocations')
                text = (address, data[fileoff:fileoff + length])
        elif command == 2:
            symbols = struct.unpack_from('<IIII', data, offset + 8)
        offset += size
    if text is None or symbols is None: raise ValueError('missing text or symbols')
    start, count, strings, _ = symbols
    ret = None
    for i in range(count):
        index, _, _, _, value = struct.unpack_from('<IBBHQ', data, start + i * 16)
        end = data.index(b'\0', strings + index)
        if data[strings + index:end] == b'_VMAppleAccountSysctlStubReturnV1': ret = value - text[0]
    if ret is None or text[1][ret:ret + 4] != struct.pack('<I', 0x14000000):
        raise ValueError('missing return branch placeholder')
    return text[1], ret


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', required=True, type=Path)
    args = parser.parse_args()
    lines = ['// Generated by build-apple-account-stubs-v1.py from the accompanying assembly.',
             '#pragma once', '#include <stdint.h>']
    with tempfile.TemporaryDirectory(prefix='vm-account-stubs-', dir='/private/tmp') as tmp:
        for name, comm in [('Proc5CC', '0x5cc'), ('Proc5BC', '0x5bc')]:
            obj = Path(tmp) / (name + '.o')
            subprocess.run(['xcrun', '--sdk', 'iphoneos', 'clang', '-target', 'arm64-apple-ios16.1',
                '-DVM_APPLE_ACCOUNT_PROC_COMM=' + comm, '-c', str(SOURCE), '-o', str(obj)], check=True)
            data, ret = extract(obj.read_bytes())
            lines += [f'static const uint8_t VMAppleAccountSysctl{name}V1[] = {{']
            for at in range(0, len(data), 16):
                lines.append('    ' + ','.join(f'0x{b:02x}' for b in data[at:at + 16]) + ',')
            lines += ['};', f'static const unsigned VMAppleAccountSysctl{name}ReturnV1 = {ret};']
            print(name, 'bytes', len(data), 'return offset', ret)
    args.output.write_text('\n'.join(lines) + '\n')


if __name__ == '__main__': main()
