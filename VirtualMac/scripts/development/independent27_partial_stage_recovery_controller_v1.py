def verify_products(scope, staged=False, include_cd=False):
    lines = ['''verify_dir() {
 [ -d "$1" ] && [ ! -L "$1" ]
 [ "$(stat -c %u:%g:%a "$1")" = "501:501:$2" ]
 [ "$(realpath "$1")" = "$1" ]
}
verify_file() {
 [ -f "$1" ] && [ ! -L "$1" ]
 [ "$(stat -c %u:%g:%a:%h:%s "$1")" = "501:501:$4:1:$3" ]
 [ "$(sha256sum "$1" | cut -d ' ' -f1)" = "$2" ]
}
verify_cd() {
 own_cd=$(ldid -h "$1" 2>&1)
 [ "$(printf '%s\\n' "$own_cd" | sed -n 's/^CDHash=//p')" = "$2" ]
}
''']
    for name, mode in sorted(scope['directories'].items()):
        path = DEVICE_STAGE+'/'+name if staged else (DEVICE_RUNTIME+name[len('runtime'):] if name.startswith('runtime') else DEVICE_APP+name[len('VirtualMacIndependent27.app'):])
        lines.append(f'verify_dir {shlex.quote(path)} {mode:o}\n')
    for row in scope['files']:
        path = DEVICE_STAGE+'/'+row['archivePath'] if staged else row['devicePath']
        lines.append(f'verify_file {shlex.quote(path)} {row["local"]["sha256"]} {row["local"]["bytes"]} {row["mode"]:o}\n')
        if include_cd and row.get('cdhash'):
            lines.append(f'verify_cd {shlex.quote(path)} {row["cdhash"]}\n')
    for top in ('runtime', 'VirtualMacIndependent27.app'):
        count = sum(name != top and name.startswith(top+'/') for name in scope['directories'])+sum(row['archivePath'].startswith(top+'/') for row in scope['files'])
        path = DEVICE_STAGE+'/'+top if staged else DEVICE_RUNTIME if top == 'runtime' else DEVICE_APP
        lines.append(f'[ "$(find {shlex.quote(path)} -mindepth 1 | wc -l | tr -d \' \')" = {count} ]\n')
    lines.append('printf \'INDEPENDENT27_ALL_ACTUAL_PRODUCTS_EXACT\\n\'\n')
    return ''.join(lines)


